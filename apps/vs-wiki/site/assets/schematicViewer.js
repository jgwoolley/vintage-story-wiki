// Schematic viewer (site/tools/schematic/index.njk): a schematic adapter on the shared
// voxelViewer.js core, the way recipeVoxels.js is the recipe adapter. Reads a Vintage Story
// schematic .json (uploaded, or one of the bundled samples), turns Indices/BlockIds into voxels,
// and layers the legend / floor slider / click-inspector UI on top. Block-entity attribute blobs
// are decoded with the shared schematicDecode.js, never a second copy.
//
// Schematic axes: each Indices entry packs a position as x = i & 0x3FF, z = (i >> 10) & 0x3FF,
// y = (i >> 20) & 0x3FF (y is up); BlockIds[n] indexes BlockCodes for the block at Indices[n].
import { createVoxelViewer } from "./voxelViewer.js";
import { decodeBlockEntity } from "./schematicDecode.js";
import { assertSchematic, fetchGzipText, isHiddenByDefault, stringToColor, toVoxels } from "./schematicVoxels.js";

const root = document.getElementById("schematicTool");
const $ = (id) => document.getElementById(id);
const els = {
  viewport: $("viewport"), legend: $("legend"), slider: $("layerSlider"), layerLabel: $("layerLabel"),
  search: $("searchInput"), info: $("schematicInfo"), size: $("sizeValue"), error: $("schematicError"),
  overlay: $("loadingOverlay"), inspector: $("inspector"), traits: $("traitContent"),
};
const samplesBase = root.dataset.samplesBase;
const worldBase = root.dataset.worldBase; // the wiki's own worldgen schematics, gzip-compressed (see src/ingest/schematicFiles.ts)
const LARGE_BYTES = 5e6;
const itemsUrl = root.dataset.itemsUrl;
// "domain:code" -> localized name, generated by the ingest pipeline (models/blockNames.ts) from the
// same lang files as the rest of the wiki. Best-effort: the legend falls back to the raw code.
let blockNames = {};
fetch(root.dataset.blockNames).then((r) => (r.ok ? r.json() : {})).then((n) => { blockNames = n; renderLegend(); }).catch(() => {});

function displayName(code) {
  // Exact match first, then drop trailing "-state" segments (orientation, variant) until one matches.
  for (let c = code; c; c = c.includes("-") ? c.slice(0, c.lastIndexOf("-")) : "") {
    if (blockNames[c]) return blockNames[c];
  }
  return code.replace(/^game:/, "").replace(/-/g, " ");
}

let viewer = null;
let data = null;
let voxels = [];
let blockMeta = new Map(); // block code -> { color, visible, count }
let currentLayer = -1;
let layerMode = "below"; // "single" = only floor N, "below" = floor N and every floor beneath it
let selectedIndex = -1;
let searchQuery = "";
let current = null; // { text, name } of the loaded schematic, so it can be downloaded back out unchanged

function showError(message) {
  els.error.textContent = message;
  els.error.hidden = !message;
}

function restyle() {
  if (!viewer) return;
  viewer.setStyle((voxel, index) => {
    if (!blockMeta.get(voxel.code).visible) return null;
    if (currentLayer !== -1 && (layerMode === "below" ? voxel.y > currentLayer : voxel.y !== currentLayer)) return null;
    const color = blockMeta.get(voxel.code).color;
    return index === selectedIndex ? { color: "#00ffff" } : { color };
  });
}

function textEl(tag, className, text) {
  const el = document.createElement(tag);
  if (className) el.className = className;
  el.textContent = text;
  return el;
}

function renderLegend() {
  els.legend.replaceChildren();
  const entries = [...blockMeta.entries()]
    .filter(([code]) => code.toLowerCase().includes(searchQuery) || displayName(code).toLowerCase().includes(searchQuery))
    .sort((a, b) => b[1].count - a[1].count);
  for (const [code, meta] of entries) {
    const item = document.createElement("button");
    item.type = "button";
    item.className = `legend-item${meta.visible ? "" : " hidden-block"}`;
    item.setAttribute("aria-pressed", String(meta.visible));
    const swatch = textEl("span", "color-box", "");
    swatch.style.background = meta.color;
    const name = textEl("span", "block-name", displayName(code));
    name.title = code;
    item.append(swatch, name, textEl("span", "block-count", `x${meta.count}`));
    item.addEventListener("click", () => {
      meta.visible = !meta.visible;
      restyle();
      renderLegend();
    });
    els.legend.append(item);
  }
}

function setAllVisible(visible) {
  blockMeta.forEach((m) => (m.visible = visible));
  restyle();
  renderLegend();
}

function closeInspector() {
  els.inspector.hidden = true;
  selectedIndex = -1;
  restyle();
}

function showInspector(voxel) {
  const entity = data.BlockEntities?.[voxel.packed];
  const ascii = typeof entity === "string" ? entity : entity?.Data || entity?.Attributes;
  els.traits.replaceChildren();
  const trait = (label, value, href) => {
    const row = textEl("div", "trait", "");
    let content = value;
    if (href) {
      content = document.createElement("a");
      content.href = href;
      content.textContent = value;
    }
    row.append(textEl("b", "", label), document.createElement("br"), content);
    els.traits.append(row);
  };
  // Both link to the wiki's items search for this block. Item pages are keyed by the asset folder
  // ("survival"), not the schematic's "game:" domain, so search on the bare code instead.
  const itemsLink = `${itemsUrl}?q=${encodeURIComponent(voxel.code.replace(/^[^:]+:/, ""))}`;
  trait("Block:", displayName(voxel.code), itemsLink);
  trait("Code:", voxel.code, itemsLink);
  trait("Position:", `X:${voxel.x}, Y:${voxel.y}, Z:${voxel.z}`);
  if (ascii) {
    try {
      const json = JSON.stringify(decodeBlockEntity(ascii), (k, v) => (typeof v === "bigint" ? v.toString() : v), 2);
      els.traits.append(textEl("div", "trait", "Entity Data:"), textEl("pre", "schematic-json", json));
    } catch (err) {
      console.error(err);
      els.traits.append(textEl("div", "trait schematic-error", `Error parsing data: ${err.message}`));
    }
  }
  els.inspector.hidden = false;
}

function load({ data: schematic, text, name }) {
  assertSchematic(schematic);
  data = schematic;
  current = { text, name };
  $("download").disabled = false;
  voxels = toVoxels(schematic);
  blockMeta = new Map();
  for (const v of voxels) {
    if (!blockMeta.has(v.code)) blockMeta.set(v.code, { color: stringToColor(v.code), visible: !isHiddenByDefault(v.code), count: 0 });
    blockMeta.get(v.code).count++;
  }
  currentLayer = -1;
  selectedIndex = -1;
  els.inspector.hidden = true;
  els.slider.max = Math.max(0, (schematic.SizeY || 1) - 1);
  els.slider.value = -1;
  els.slider.disabled = false;
  stopAutoPlay();
  autoPlay.disabled = false;
  els.layerLabel.textContent = "All Floors";
  if (schematic.SizeX && schematic.SizeY && schematic.SizeZ) {
    els.size.textContent = `${schematic.SizeX}x × ${schematic.SizeY}y × ${schematic.SizeZ}z`;
    els.info.hidden = false;
  }

  viewer?.dispose();
  viewer = createVoxelViewer(els.viewport, { voxels, label: "3D view of the loaded schematic" });
  if (!viewer) {
    showError("WebGL is unavailable in this browser, so the 3D view can't be shown.");
    return;
  }
  restyle();
  renderLegend();
}

async function withLoading(task) {
  showError("");
  els.overlay.hidden = false;
  try {
    // Yield once so the overlay paints before the heavy synchronous work begins.
    await new Promise((r) => setTimeout(r, 30));
    load(await task());
  } catch (err) {
    console.error(err);
    showError(`Failed to load schematic: ${err.message}`);
  } finally {
    els.overlay.hidden = true;
  }
}

// A task resolves to { text, name }; the text is kept for the Download button and parsed here.
const parsed = ({ text, name }) => ({ data: JSON.parse(text), text, name });
const loadFile = (file) => withLoading(async () => parsed({ text: await file.text(), name: file.name }));
$("fileInput").addEventListener("change", (e) => {
  const file = e.target.files[0];
  e.target.value = ""; // allow re-selecting the same file
  if (file) loadFile(file);
});
const dropzone = $("dropzone");
for (const type of ["dragenter", "dragover"]) {
  dropzone.addEventListener(type, (e) => { e.preventDefault(); dropzone.classList.add("dragover"); });
}
for (const type of ["dragleave", "drop"]) {
  dropzone.addEventListener(type, (e) => { e.preventDefault(); dropzone.classList.remove("dragover"); });
}
dropzone.addEventListener("drop", (e) => {
  const file = e.dataTransfer?.files?.[0];
  if (file) loadFile(file);
});
$("fileSelect").addEventListener("change", (e) => {
  if (!e.target.value) return;
  withLoading(async () => {
    const response = await fetch(samplesBase + e.target.value);
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    return parsed({ text: await response.text(), name: e.target.value });
  });
});
els.search.addEventListener("input", (e) => {
  searchQuery = e.target.value.toLowerCase();
  renderLegend();
});
$("clearSearch").addEventListener("click", () => {
  els.search.value = "";
  searchQuery = "";
  renderLegend();
});
els.slider.addEventListener("input", (e) => {
  currentLayer = parseInt(e.target.value, 10);
  updateLayerLabel();
  restyle();
});
for (const btn of document.querySelectorAll(".layer-mode")) {
  btn.addEventListener("click", () => {
    layerMode = btn.dataset.mode;
    document.querySelectorAll(".layer-mode").forEach((b) => {
      b.classList.toggle("active", b === btn);
      b.setAttribute("aria-pressed", String(b === btn));
    });
    updateLayerLabel();
    restyle();
  });
}
// Auto-play: advance the floor slider on a timer, wrapping from the top floor back to the bottom.
const autoPlay = $("autoPlay");
const autoPlaySpeed = $("autoPlaySpeed");
let autoTimer = null;
function stopAutoPlay() {
  clearInterval(autoTimer);
  autoTimer = null;
  autoPlay.innerHTML = "&#9654; Auto-play";
  autoPlay.classList.remove("active");
  autoPlay.setAttribute("aria-pressed", "false");
}
function stepFloor() {
  const top = Number(els.slider.max);
  currentLayer = currentLayer >= top ? 0 : currentLayer + 1; // -1 ("all floors") -> floor 0
  els.slider.value = currentLayer;
  updateLayerLabel();
  restyle();
}
function startAutoPlay() {
  autoPlay.innerHTML = "&#9632; Pause";
  autoPlay.classList.add("active");
  autoPlay.setAttribute("aria-pressed", "true");
  stepFloor();
  autoTimer = setInterval(stepFloor, Number(autoPlaySpeed.value));
}
autoPlay.addEventListener("click", () => (autoTimer ? stopAutoPlay() : startAutoPlay()));
autoPlaySpeed.addEventListener("change", () => {
  if (!autoTimer) return;
  stopAutoPlay();
  startAutoPlay();
});
// Dragging the slider by hand takes over from playback.
els.slider.addEventListener("input", () => autoTimer && stopAutoPlay());

function updateLayerLabel() {
  els.layerLabel.textContent = currentLayer === -1 ? "All Floors" : layerMode === "below" ? `Floors 0\u2013${currentLayer}` : `Floor Y: ${currentLayer}`;
}
$("showAll").addEventListener("click", () => setAllVisible(true));
$("hideAll").addEventListener("click", () => setAllVisible(false));
$("resetView").addEventListener("click", () => viewer?.resetView());
$("closeInspector").addEventListener("click", closeInspector);
// Download the loaded schematic back out, byte for byte as it was read (an upload, a sample, or the
// unpacked copy of one of the wiki's own).
$("download").addEventListener("click", () => {
  if (!current) return;
  const url = URL.createObjectURL(new Blob([current.text], { type: "application/json" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = current.name.endsWith(".json") ? current.name : `${current.name}.json`;
  document.body.append(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
});

// A click that isn't a drag: OrbitControls swallows nothing, so tell the two apart by distance.
let down = null;
els.viewport.addEventListener("pointerdown", (e) => (down = [e.clientX, e.clientY]));
els.viewport.addEventListener("pointerup", (e) => {
  if (!viewer || !down || Math.hypot(e.clientX - down[0], e.clientY - down[1]) > 4) return;
  const hit = viewer.pick(e.clientX, e.clientY);
  if (!hit) return closeInspector();
  selectedIndex = hit.index;
  restyle();
  showInspector(hit.voxel);
});

// Fetches a gzip copy of one of the wiki's own schematics and decompresses it in the browser.
async function fetchWorldSchematic(path) {
  const text = await fetchGzipText(`${worldBase}${path}.json.gz`, (length) => {
    if (length > LARGE_BYTES / 5) els.overlay.querySelector("#loadingText").textContent = "Downloading and unpacking a large schematic...";
  });
  return parsed({ text, name: `${path.split("/").pop()}.json` });
}

// `?schematic=<domain>/<relPath>` (linked from the schematic and structure pages) opens one of the
// wiki's own worldgen schematics; otherwise start on the default sample so the page isn't empty.
const requested = new URLSearchParams(location.search).get("schematic");
if (requested && /^[\w.-]+(\/[\w. +()-]+)+$/.test(requested) && !requested.includes("..")) {
  const [domain, ...rest] = requested.split("/");
  const relPath = rest.join("/");
  const link = $("worldSchematicLink");
  link.textContent = relPath;
  link.href = `${root.dataset.schematicsUrl}${domain}/${relPath.toLowerCase()}/`; // SchematicInfo.pagePath
  $("worldSchematic").hidden = false;
  $("downloadGz").href = `${worldBase}${requested}.json.gz`;
  $("downloadGz").download = `${relPath.split("/").pop()}.json.gz`;
  $("downloadGz").hidden = false;
  withLoading(() => fetchWorldSchematic(requested));
} else {
  $("fileSelect").value = "default.json";
  $("fileSelect").dispatchEvent(new Event("change"));
}
