// Auto-play: advance the floor slider on a timer, wrapping from the top floor back to the bottom.
const autoPlay = $("autoPlay");
const autoPlaySpeed = $("autoPlaySpeed");
let autoTimer = null;
function stopAutoPlay() {
  clearInterval(autoTimer);
  autoTimer = null;
  autoPlay.innerHTML = "&#9654; Auto-play";
  autoPlay.classList.remove("active");
  autoPlay.setAttribute("aria-pressed", "false");
}
function stepFloor() {
  const top = Number(els.slider.max);
  currentLayer = currentLayer >= top ? 0 : currentLayer + 1; // -1 ("all floors") -> floor 0
  els.slider.value = currentLayer;
  updateLayerLabel();
  restyle();
}
function startAutoPlay() {
  autoPlay.innerHTML = "&#9632; Pause";
  autoPlay.classList.add("active");
  autoPlay.setAttribute("aria-pressed", "true");
  stepFloor();
  autoTimer = setInterval(stepFloor, Number(autoPlaySpeed.value));
}
autoPlay.addEventListener("click", () => (autoTimer ? stopAutoPlay() : startAutoPlay()));
autoPlaySpeed.addEventListener("change", () => {
  if (!autoTimer) return;
  stopAutoPlay();
  startAutoPlay();
});
// Dragging the slider by hand takes over from playback.
els.slider.addEventListener("input", () => autoTimer && stopAutoPlay());

function updateLayerLabel() {
  els.layerLabel.textContent = currentLayer === -1 ? "All Floors" : layerMode === "below" ? `Floors 0\u2013${currentLayer}` : `Floor Y: ${currentLayer}`;
}
